#!/usr/bin/env node
// Collects every [CONFIRM: …], [PRICE], TODO and other placeholder in the code into CONTENT-TODO.md,
// so the list can never drift from the site. Run: npm run todo
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOTS = ["src", "content"];
const PATTERN =
  /\[CONFIRM[^\]]*\]|\[PRICE\]|\[THANKSGIVING_FORM_URL\]|\[SITE CREDIT\]|\[BAKER FIRST NAME[^\]]*\]|TODO[:\s][^*\n]*/g;

const walk = (dir) =>
  readdirSync(dir).flatMap((f) => {
    const p = path.join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : /\.(tsx?|csv|md)$/.test(f) ? [p] : [];
  });

const hits = new Map();
for (const file of ROOTS.flatMap(walk)) {
  if (file.endsWith(".test.ts")) continue;
  readFileSync(file, "utf8")
    .split("\n")
    .forEach((line, i) => {
      for (const m of line.matchAll(PATTERN)) {
        let key = m[0].replace(/\s+$/, "").replace(/[`"';,)]+$/, "");
        if (key === "[CONFIRM: …]") continue; // the example in a code comment
        key = key.replace(/ before launch\.?$/, "");
        if (!hits.has(key)) hits.set(key, []);
        hits.get(key).push(`${file}:${i + 1}`);
      }
    });
}

hits.delete("[PRICE]");
const menuSrc = readFileSync("src/content/menu.ts", "utf8");
const price = menuSrc.match(/price: (P|"\[PRICE\]")[,\s}]/g) ?? [];
const groups = [...hits.entries()].sort((a, b) => a[0].localeCompare(b[0]));

const md = `# Content to confirm before launch

Generated by \`npm run todo\` from the placeholders in the code. Nothing below is shown on the site
as a fact until it's confirmed. Fix the value in the file listed, then re-run \`npm run todo\`.

## Needs an answer from the owner

| Placeholder | Where |
|---|---|
${groups.map(([k, where]) => `| \`${k.replace(/\|/g, "\\|")}\` | ${[...new Set(where)].map((w) => `\`${w}\``).join("<br>")} |`).join("\n")}

## Prices

Only the Thanksgiving 2026 pre-order prices and the Butter Pecan Sticky Buns ($12, from the chalkboard)
are shown. **${price.length} menu items** in \`src/content/menu.ts\` have no price yet (\`price: P\`, i.e. \`"[PRICE]"\`), which the site
never displays. Fill in real numbers there if you want prices on the menu page.

## Also decide

- **Domain**: set \`NEXT_PUBLIC_SITE_URL\` (canonical links, sitemap and social previews use it).
- **Testimonials**: every quote in \`src/content/testimonials.ts\` is from a public Facebook comment and
  shows first name + last initial. Confirm the owner is happy to feature them.
- **Logo colour**: the original logo's ink is a near-black brown and "BAKERY" is charcoal grey; the
  site uses the brief's crust brown (#5B3A24) for both. Say if it should match the original exactly.
- **Thanksgiving form**: paste the real Google Form link into \`THANKSGIVING_FORM_URL\` in
  \`src/content/preorders.ts\`. Until then the site's own request form is the only way to order.
`;
writeFileSync("CONTENT-TODO.md", md);
console.log(`CONTENT-TODO.md: ${groups.length} placeholders, ${price.length} [PRICE] items`);
