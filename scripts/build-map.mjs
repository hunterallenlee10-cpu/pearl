#!/usr/bin/env node
// Builds the illustrated map's line art from real geography (US Census TIGER roads + water,
// saved in scripts/map-source/). Output: src/components/visit/map-data.ts
//
// Re-fetch the source (optional):
//   B="-76.70,38.22,-76.57,38.31"; base=https://tigerweb.geo.census.gov/arcgis/rest/services/TIGERweb
//   curl "$base/Transportation/MapServer/6/query?where=1%3D1&geometry=$B&geometryType=esriGeometryEnvelope&inSR=4326&outSR=4326&outFields=*&f=json" > scripts/map-source/sec.json
//   (layer 8 → local.json, Hydro/MapServer/1 → water.json)
import { readFileSync, writeFileSync } from "node:fs";

const load = (f) => JSON.parse(readFileSync(`scripts/map-source/${f}.json`, "utf8")).features;
const sec = load("sec");
const local = load("local");
const water = load("water");

// Frame: Leonardtown to the farmstand, with Breton Bay in between.
const BOX = { west: -76.668, east: -76.588, south: 38.247, north: 38.302 };
const kx = Math.cos((38.275 * Math.PI) / 180);
const W = 1000;
const H = Math.round((W * (BOX.north - BOX.south)) / ((BOX.east - BOX.west) * kx));
const px = ([lon, lat]) => [
  ((lon - BOX.west) / (BOX.east - BOX.west)) * W,
  ((BOX.north - lat) / (BOX.north - BOX.south)) * H,
];

function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const sq = (a, b) => (a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2;
  const segDist = (p, a, b) => {
    const l = sq(a, b);
    if (!l) return sq(p, a);
    let t = ((p[0] - a[0]) * (b[0] - a[0]) + (p[1] - a[1]) * (b[1] - a[1])) / l;
    t = Math.max(0, Math.min(1, t));
    return sq(p, [a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1])]);
  };
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [s, e] = stack.pop();
    let max = 0,
      idx = -1;
    for (let i = s + 1; i < e; i++) {
      const d = segDist(pts[i], pts[s], pts[e]);
      if (d > max) [max, idx] = [d, i];
    }
    if (max > tol * tol) {
      keep[idx] = 1;
      stack.push([s, idx], [idx, e]);
    }
  }
  return pts.filter((_, i) => keep[i]);
}

const r = (n) => Math.round(n * 10) / 10;
const toD = (lines, close = false) =>
  lines
    .map((pts) => pts.map((p, i) => `${i ? "L" : "M"}${r(p[0])} ${r(p[1])}`).join("") + (close ? "Z" : ""))
    .join("");

const inFrame = (pts) => pts.some(([x, y]) => x > -60 && x < W + 60 && y > -60 && y < H + 60);
const lines = (features, tol, filter = () => true) =>
  features
    .filter(filter)
    .flatMap((f) => f.geometry.paths)
    .map((p) => simplify(p.map(px), tol))
    .filter(inFrame);

const name = (f) => f.attributes.NAME || "";
const medleys = lines(sec, 0.8, (f) => name(f) === "Medleys Neck Rd");
const major = lines(sec, 1.2, (f) => name(f) !== "Medleys Neck Rd");

// Local streets: downtown Leonardtown plus the lanes off Medley's Neck near the stand.
const town = px([-76.6355, 38.2912]);
const stand = px([-76.61549, 38.27239]);
const near = (pts, c, rad) => pts.some(([x, y]) => Math.hypot(x - c[0], y - c[1]) < rad);
const localLines = lines(local, 1.4).filter((pts) => near(pts, town, 150) || near(pts, stand, 70));

const waterRings = water
  .flatMap((f) => f.geometry.rings)
  .map((ring) => simplify(ring.map(px), 1.4))
  .filter((ring) => ring.length > 3 && inFrame(ring));

const bay = water.find((f) => name(f) === "Breton Bay");
const bayLabel = [300, 560]; // on open water of the bay (map units)
void bay;

const out = `// Generated by scripts/build-map.mjs from US Census TIGER data. Do not edit by hand.
export const mapBox = { width: ${W}, height: ${H} };
export const mapWater = ${JSON.stringify(toD(waterRings, true))};
export const mapMajorRoads = ${JSON.stringify(toD(major))};
export const mapLocalRoads = ${JSON.stringify(toD(localLines))};
export const mapMedleysNeck = ${JSON.stringify(toD(medleys))};
export const mapPoints = {
  leonardtown: [${r(town[0])}, ${r(town[1])}],
  farmstand: [${r(stand[0])}, ${r(stand[1])}],
  bretonBay: [${r(bayLabel[0])}, ${r(bayLabel[1])}],
} as const;
`;
writeFileSync("src/components/visit/map-data.ts", out);
console.log(
  `map ${W}x${H}; water ${waterRings.length} rings, major ${major.length}, local ${localLines.length}, medleys ${medleys.length}; ${out.length} bytes`,
);
